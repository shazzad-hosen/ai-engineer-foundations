# class is a blueprint of an object
class Student:
    college = "ABC college of Engineering"
    subject = "Python"
    year = "3rd"
    

# objects, object is an instance of class
student1 = Student()
student2 = Student()

print(student1)
print(student2)

print(student1.college)
print(student2.college)

print(student1.subject)
print(student2.subject)

print(student1.year)
print(student2.year)